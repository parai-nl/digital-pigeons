const en = { ...graphEn, ...readingEn }
const nl: Record<keyof typeof en, string> = { ...graphNl, ...readingNl }
export type GraphKey = keyof typeof en

export function graphTranslator(locale: UiLocale): (key: GraphKey, vars?: Record<string, string | number>) => string {
  return (key, vars) => interpolate((locale.lang === 'nl' ? nl : en)[key], vars)
}
